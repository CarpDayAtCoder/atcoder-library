// ============================================================
// 尺取り法テンプレート
//
// 使用頻度：★★★★☆
// 主な用途：条件を満たす連続部分列の最大長・最小長・個数など
// キーワード：尺取り法，two pointers，sliding window，tail，head
//
// 【基本】
// 現在の区間を [tail, head) として管理する．
// headは区間に含まれず，次に追加しようとしている位置を表す．
//   tail             head
//     ↓                ↓
//     [ ● ● ● ● ● )
//       現在の区間
// headは後戻りせず，条件を満たす間だけ右へ進める．
// tailも左から右へ1回ずつ進むため，全体でO(N)になる．
//
// 【使用条件】
// headを右へ進めたときの条件変化に単調性が必要．
// 例：A[i] >= 0 のとき，区間和は要素を追加すると減らないため，
//     「区間和 <= K」には尺取り法を使用できる．
// 負の値がある場合など，headを進めることで一度満たさなくなった
// 条件が再び満たされる可能性がある場合は，そのまま使用できない．
//
// 【計算量】
// tailは最大N回，headも最大N回しか進まないためO(N)．
//
// 【注意】
// 【1】区間は [tail, head)
//     区間の長さは  head - tail
//     A[head]はまだ区間に含まれていない．
//
// 【2】追加処理をしてからheadを進める
//     sum += A[head];
//     head++;
//
// 【3】tailを進める前にA[tail]を区間から取り除く
//     sum -= A[tail];
//
// 【4】head == tail の場合
//     A[tail]を1つも区間へ追加できなかった場合，head == tail となる．
//     このときA[tail]は区間に入っていないので削除せず，headだけ右へ進める．
//     if (head == tail) head++;
//     else              sum -= A[tail];
//
// ============================================================

// ============================================================
// 実戦用テンプレート
//
// 例：
// A[i] >= 0 の数列について，
// 区間和がK以下となる連続部分列の最大長を求める．
//
// 問題に応じて，
//   ・区間の状態
//   ・追加可能条件
//   ・追加処理
//   ・答え更新
//   ・削除処理
// を変更する．
// ============================================================
