#include <bits/stdc++.h>
#ifdef _WIN32
#include <windows.h>
#endif
using namespace std;


// ============================================================
// 全列挙 まとめ
//
// 使用頻度：★★★★☆
// 主な用途：順列，組合せ，部分集合，n進数パターン，直積の全探索
//
// 1．順列全列挙             next_permutation
// 2．組合せ全列挙           0/1列 + next_permutation
// 3．部分集合（bit）全列挙  0 ～ (1<<N)-1
// 4．K進数全列挙            0 ～ K^N-1 をK進数として見る
// 5．直積全列挙             views::cartesian_product
//
// ============================================================

int main() {
#ifdef _WIN32
    SetConsoleOutputCP(CP_UTF8);
#endif

    // ========================================================
    // 1．順列全列挙
    // ========================================================
    cout << "##### 1．順列全列挙(1,2,3) #####\n";

    vector A{1, 2, 3};      // A（ソート済み）の全順列を辞書順に列挙する
    do {
        for (int x : A) cout << x;
        cout << '\n';
    } while (next_permutation(A.begin(), A.end()));


    // ========================================================
    // 2．組合せ全列挙
    // ========================================================
    cout << "\n##### 2．組合せ全列挙 (0,1,2,3,4)から2個 #####\n";

    int n = 5;
    int k = 2;
    vector<int> use(n);                 // n個すべて0で初期化
    fill(use.end() - k, use.end(), 1);  //後ろk個を1に．useはソート済み結果と同じ
    do {
        for (int i=0; i<n; i++) {
            if (use[i]) cout << i << ' ';
        }
        cout << '\n';
    } while (next_permutation(use.begin(), use.end())); // 同じ順列は生成しない


    // ========================================================
    // 3．部分集合（bit）全列挙
    // ========================================================
    cout << "\n##### 3．部分集合（bit）全列挙 #####\n";

    n = 3;
    for (int mask=0; mask<(1<<n); mask++) {     // 0～2^n -1まで
    // for (ll mask=0; mask<(1LL<<n); mask++) {     // nが大きい場合 
        cout << mask << ": ";
        for (int i=0; i<n; i++) {   // 各bitをチェック
            if (mask >> i & 1) cout << i << ' ';    // 1なら含む
        }
        cout << '\n';
    }


    // ========================================================
    // 4．K進数全列挙
    // ========================================================
    cout << "\n##### 4．k進数全列挙 (k=3, n=2桁) #####\n";

    n = 2;
    k = 3;
    long long total = 1;
    for (int i=0; i<n; i++) total *= k; // k進数n桁で表現できる種類数

    for (long long mask=0; mask<total; mask++) {
        long long x = mask;
        vector<int> pat(n);
        for (int i=n-1; i>=0; i--) {
            pat[i] = x % k;
            x /= k;
        }
        for (int p : pat) cout << p;
        cout << '\n';
    }


    // ========================================================
    // 5．直積全列挙
    // ========================================================
    cout << "\n##### 5．直積全列挙 [A,B,C]×[0,1]#####\n";
    vector S{'A', 'B', 'C'};
    vector X{0, 1};
    for (auto [s, a] : views::cartesian_product(S, X)) {
        cout << s << a << '\n';
    }


    return 0;
}


// ============================================================
// 補足
// ============================================================
// 1．順列全列挙
//
// 【重要】全順列を列挙する場合は，最初に昇順sortしておく．
// 
// next_permutationは現在の並びを「次の辞書順」に変更する．
//
// 最後の順列まで到達するとfalseを返し，並び自体は最初の順列に戻る．
//
// ============================================================
// 2．組合せ全列挙
//
// N個からK個を選ぶ全組合せを列挙する．0/1列で「選ぶ位置」を表す．
// 例えばN=5，K=2なら
//   00011
//   00101
//   00110
//   01001
//   ...
// のように，「1がK個ある0/1列」の順列を列挙する．
// next_permutationは同じ順列は生成しないため，組合せにも対応できる．
//
// 選んだ要素自体が必要なら，use[i]==1のiから取得する．
//
// ============================================================
// 3．部分集合（bit）全列挙
//
// N個の要素について，選ぶ／選ばないの全2^N通りを列挙する．
// 計算量：O(N × 2^N)
//
// maskのi bit目が
//   1 → iを選ぶ
//   0 → iを選ばない
//
// 判定：
//   if (mask >> i & 1)
// または
//   if (mask & (1 << i))
//
// bitsetを使うこともできるが，
// 単純な全列挙では整数maskの方が扱いやすいことが多い．
//
// ============================================================
// 4．K進数全列挙
//
// 0～K-1をN個並べる全K^N通りを列挙する．計算量：O(N × K^N)
// 
// maskをK進数で表した各桁をpatと考える．
//   pat[i] = x % K;
//   x /= K;
// を繰り返して各桁を取り出す．
//
// 2進数の場合は3．bit全列挙の方が簡単．
//
// ============================================================
// 5．直積全列挙
//
// 列の個数が固定なら，views::cartesian_product が使える．
//
// vector A{0, 1, 2};
//
// for (auto [a, b, c] : views::cartesian_product(A, A, A)) {
//     ...
// }
//
// ※ 繰返し回数Nが実行時に決まる場合は，
//    4．n進数全列挙の方が使いやすい．
//
// ============================================================