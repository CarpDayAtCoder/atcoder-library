#include <bits/stdc++.h>
#ifdef _WIN32
#include <windows.h>
#endif
using namespace std;
using ll = long long;

// ============================================================
// 最大流・最小カット まとめ
//
// 使用頻度：★★★☆☆
// 主な用途：最大流，最小カット，最大重み閉包，燃やす埋める問題など
// キーワード：maxflow，mincut，mf_graph，flow，add_edge，min_cut
//
// 【基本】
// mf_graph<ll> g(N);             // N頂点無枝グラフの作成．頂点番号 0～N-1
// g.add_edge(u, v, cap);         // 有向辺(u, v)の追加．容量cap
// ll max_flow = g.flow(s, t);    // s → t の最大流
// auto cut = g.min_cut(s);       // 最小カット
//    cut[v] == true  ：S側（sから残余グラフで到達可能）
//    cut[v] == false ：T側
//
// ※ 容量が大きくなる可能性がある場合は，mf_graph<ll>を使用する．
// 計算量：O(EV^2)
//
// ============================================================
// 【最小カット】
//
// 頂点を
//   S側：sを含む
//   T側：tを含む
// に分割する S → T の辺だけがカットされ，その容量の合計を最小化する．
//
// 最大流量 = 最小カット容量
// T → S の辺はカット容量に含まれないことに注意．
//
// ============================================================

#include <atcoder/maxflow>
using namespace atcoder;

int main() {
#ifdef _WIN32
    SetConsoleOutputCP(CP_UTF8);
#endif
    //     10                 最大流 = 4
    //  s -----> (1)          
    //   ＼       |  ＼1      最小カット：  
    //    1＼    2|    ＼       S = {s, 1}
    //       ＼   v      ＼v    T = {2, t}
    //          >(2)-----> t
    //                10
    //
    int s = 0, t = 3;
    mf_graph<ll> g(4);
    g.add_edge(s, 1, 10);
    g.add_edge(s, 2, 1);
    g.add_edge(1, t, 1);
    g.add_edge(2, t, 10);
    g.add_edge(1, 2, 2);

    ll max_flow = g.flow(s, t);     // 最大流問題を解く
    cout << "最大流: " << max_flow << '\n';

    auto cut = g.min_cut(s);
    cout << "S側: ";            // S側の点
    for (int v=0; v<4; v++) {
        if (cut[v]) cout << v << ' ';
    }
    cout << '\n';
    cout << "T側: ";            // T側の点
    for (int v=0; v<4; v++) {
        if (!cut[v]) cout << v << ' ';
    }
    cout << '\n';

    return 0;
}


// ============================================================
// 補足
// ============================================================
// 辺の情報を取得
//
// 最大流後に，実際に各辺へ流れた量を確認・復元したい場合に使用．
// 例：二部マッチングでflow==1の辺を調べ，実際の組合せを復元する．
//
// 全辺を調べる場合：
// for (auto e : g.edges()) {
//     e.from;   // 始点
//     e.to;     // 終点
//     e.cap;    // 容量
//     e.flow;   // 実際の流量
// }
//
// 1つの枝を調べる場合：
// auto e = g.get_edge(i);  // i = g.add_edge(u, v, cap); の戻り値
// ============================================================
// INF容量
//
// 「この辺は絶対に切らせたくない」という制約には十分大きな容量INFを設定する．
// constexpr ll INF = 1LL << 60;
//
// ただし本質的には
//   INF > 通常の辺だけで作れるカット容量の最大値
// となればよい．
// 問題によっては
//   ll INF = 有限容量の総和 + 1;
// とする方が意味が明確．
//
// ============================================================
// ◎適用例１：最大重み閉包問題
//
// 【問題】
// 各頂点vに重みw[v]（負数もあり）がある有向グラフで，頂点集合Xを選んで
//   Σ w[v]
//   v∈X
// を最大化する．ただし，「uを選ぶなら必ずvも選ぶ」という制約がある．
//（この条件を満たす集合を「閉包」と呼ぶ．）
//
// 【実装例】
// int s = N, t = N + 1;
// mf_graph<ll> g(N + 2);
// ll base = 0;     // 正の重みを全て選んだときの合計になる
//
// for (int v=0; v<N; v++) {
//     // 正の重みの点は選ばない（T側にする）と減点 
//     if (w[v] > 0) {              // 選ぶと加点される点vは，
//         g.add_edge(s, v, w[v]);  // 有向辺 (s, v, w[v])を結ぶ
//         base += w[v];            // 正の重みを加算
//     }
//     // 負の重みの点は選ぶ（S側にする）と減点
//     else if (w[v] < 0) {         // 選ぶと減点される点vは，
//         g.add_edge(v, t, -w[v]); // 有向辺 (v, t, -w[v])を結ぶ
//     }
// }
//
// for (auto [u, v] : dependency) {
//     g.add_edge(u, v, INF);    // uを選ぶ ⇒ vも選ぶ
// }
// 最大流を計算して，制約を守りつつ，減点（カット）を最小化する
// ll ans = base - g.flow(s, t);
//
// ============================================================
// ◎適用例２：燃やす埋める問題
//
// 【問題】
// 各要素vについて「燃やす」「埋める」の2択を決め，総コストを最小化する．
// 要素単独のコストのほか，2要素間の制約・追加コストなどがある．
//
// S側 ＝ 燃やす，T側 ＝ 埋める，と考える．
//
// 各要素vの選択コスト：burn[v]：燃やすコスト，bury[v]：埋めるコスト
// 制約：
//  (1) 点vを燃やして，点uを埋めるなら，コストc（c＝∞なら禁止）
//  (2) 点vを埋めて，点uを燃やすなら，コストc（c＝∞なら禁止）
//
// 【実装例】
//
// mf_graph<ll> g(N);
//
// for (int v=0; v<N; v++) {
//     g.add_edge(v, t, burn[v]);   // v：燃やす（S側）とき，(v, t)がカット → burn[v]
//     g.add_edge(s, v, bury[v]);   // v：埋める（T側）とき，(s, v)がカット → bury[v]
// }
//
// 「uを燃やす ⇒ vも燃やす」：
// g.add_edge(u, v, INF);           // u∈S，v∈Tを禁止
//
// 「uを燃やし，vを埋めるとcostだけ追加」：
// g.add_edge(u, v, cost);          // u∈S，v∈Tのときだけコスト
//
// 「uとvが異なる選択ならcostだけ追加」：
// g.add_edge(u, v, cost);
// g.add_edge(v, u, cost);          // S,Tが異なるとどちらか一方だけカット
//
// ll ans = g.flow(s, t);           // 最小コスト = 最小カット = 最大流
//
// 最適な選択を知りたい場合：
// auto cut = g.min_cut(s);
// cut[v] == true;                  // S側：vを燃やす
// cut[v] == false;                 // T側：vを埋める
//
// ============================================================