#include <bits/stdc++.h>
#ifdef _WIN32
#include <windows.h>
#endif
using namespace std;

// ============================================================
// std::bitset まとめ
//
// 使用頻度：★★★☆☆
// 主な用途：0/1状態の管理，集合の表現，高速な集合演算
// キーワード：bitset，set，reset，flip，test，count，any，none，all，
//             &, |, ^, ~
//
// 【基本】
// constexpr int MAX_N = 200005;
// bitset<MAX_N> B;          // MAX_N個のbit．初期値はすべて0
//
// サイズはコンパイル時に決まっている必要がある．
// bit i = 1：要素iを含む
// bit i = 0：要素iを含まない
//
// 1bitの取得・変更：O(1)
// &, |, ^, countなど全体を扱う処理：おおよそO(N / word_size(CPUビット数))
//
// ============================================================
// 【生成・初期化】
//
// constexpr int MAX_N = 200005;
// bitset<MAX_N> B;          // 全bitが0
//
// bitset<8> B1("00101101"); // 2進文字列から作成
//
// vector<bitset<MAX_N>> A(k);   // bitsetをk個
//
// ============================================================
// 【主なメソッド・操作】
//
// bitset<MAX_N> B;
//
// 〇1bitの変更
//   ・B.set(i);         // bit iを1．iは0-index
//   ・B.reset(i);       // bit iを0
//   ・B.flip(i);        // bit iを反転
//   ・B[i] = 1;
//   ・B[i] = 0;
//
// 〇1bitの取得
//   ・B[i];             // bit i
//   ・B.test(i);        // bit iが1ならtrue
//
// 〇全bitの変更
//   ・B.set();          // 全bitを1
//   ・B.reset();        // 全bitを0
//   ・B.flip();         // 全bitを反転
//
// 〇状態の確認
//   ・B.count();        // 1の個数
//   ・B.any();          // 1が1つでもあればtrue
//   ・B.none();         // 全bitが0ならtrue
//   ・B.all();          // 全bitが1ならtrue
//   ・B.size();         // bit数
//
// ============================================================
// 【集合演算】
//
// bitset<MAX_N> A, B;
// A & B        // 積集合
// A | B        // 和集合
// A ^ B        // 対称差
// ~A           // bit反転（補集合に相当）
//
// A &= B;
// A |= B;
// A ^= B;
//
// 例：
// bitset<MAX_N> U;
// U |= A;      // U ← U ∪ A
//
// ============================================================
// 【シフト】
//
// B << k       // 左にk bitシフト
// B >> k       // 右にk bitシフト
// B <<= k;
// B >>= k;
//
// bit位置の差・距離をまとめて扱う問題などで使用することがある．
//
// ============================================================

int main() {
#ifdef _WIN32
    SetConsoleOutputCP(CP_UTF8);
#endif

    cout << boolalpha;

    cout << "##### 基本操作 #####\n";
    cout << " （8ビットの1, 3, 6ビット目を1）\n";
    bitset<8> A;
    A.set(1);
    A.set(3);
    A.set(6);
    cout << "A          : " << A << '\n';

    cout << "A[3]       : " << A[3] << '\n';
    cout << "A.count()  : " << A.count() << '\n';
    A.reset(3);
    cout << "reset(3)   : " << A << '\n';
    A.flip(1);
    cout << "flip(1)    : " << A << '\n';


    cout << "\n##### 集合演算 #####\n";
    bitset<8> B;
    B.set(2);
    B.set(6);
    B.set(7);
    cout << "A          : " << A << '\n';
    cout << "B          : " << B << '\n';
    cout << "A | B      : " << (A | B) << '\n';
    cout << "A & B      : " << (A & B) << '\n';
    cout << "A ^ B      : " << (A ^ B) << '\n';


    cout << "\n##### 文字列から生成 #####\n";
    bitset<8> C("00101101");
    cout << "C          : " << C << '\n';
    cout << "C[0]       : " << C[0] << '\n';

    return 0;
}


// ============================================================
// 補足
// ============================================================
// setとの使い分け
//
// 【setが向く】
// ・要素の値が大きい／飛び飛び
// ・含まれる要素数が少ない
// ・要素を昇順に管理したい
// ・最小値，最大値，lower_bound，upper_boundを使いたい
//
// 【bitsetが向く】
// ・全体集合が0～N-1などで番号化できる
// ・Nの最大値があらかじめ分かっている
// ・集合の和・積・対称差を何度も計算する
// ・共通要素数を高速に求めたい
//
// set：含まれる要素そのものを保持
// bitset：全要素について含む／含まないを0/1で保持
//
// 集合演算：
//   set     → おおよそO(|A| + |B|)
//   bitset  → おおよそO(N / word_size) ≒ O(N / 64)
//
// ※ bitsetは「setの高速版」ではなく，用途の異なる集合表現．
// ============================================================
// サイズはコンパイル時定数
//
// OK：
// constexpr int MAX_N = 200005;
// bitset<MAX_N> B;
//
// NG：
// int n;
// cin >> n;
// bitset<n> B;
//
// 入力nに応じて必要なbitだけを使いたい場合も，
// 制約上の最大値でbitsetを確保しておけばよい．
//
// ============================================================
// 集合として使う場合
//
// 全体集合が0～N-1なら，
//   bit i = 1 ⇔ 要素iを含む
// と対応させると分かりやすい．
//
// 全体集合が1～Nの場合は，bit 0を使わず
// bit 1～Nをそのまま要素番号に対応させてもよい．
//
// constexpr int MAX_N = 200005;
// bitset<MAX_N> S;
//
// S.set(x);        // xを集合に追加
// S.reset(x);      // xを集合から削除
// S.test(x);       // xが集合に含まれるか
// S.count();       // 集合の要素数
//
// ============================================================
// ~による補集合の注意
//
// ~Aはbitsetの全bitを反転する．
// bitset<MAX_N>を使って1～Nだけを集合として扱っている場合，
// Nより後ろの未使用bitも1になる．
// そのため，~Aをそのまま「1～Nに対する補集合」と考える場合は注意．
//
// ============================================================
// 文字列とのbit順
//
// bitset<8> B("00101101");
//
// 表示：
//   00101101
//          ↑
//          bit 0
// 文字列の右端がbit 0になる．
//
// B[0] == 1
// B[1] == 0
// B[2] == 1
//
// ============================================================
// vector<bool>との違い
//
// vector<bool> V(n);        // サイズを実行時に決定可能
// bitset<MAX_N> B;          // サイズはコンパイル時に固定
//
// bitsetは
//   A & B
//   A | B
//   A ^ B
// のようなbit列全体の演算ができる．
// vector<bool>では同じ書き方の全体演算はできない．
//
// ============================================================
// 1になっているbitを列挙
//
// 標準bitsetには，1になっているbitだけを順に取得する
// 標準的なiteratorはない．
//
// 必要なら普通に走査する：
//
// for (int i=0; i<N; i++) {
//     if (B[i]) {
//         ...
//     }
// }
// この処理はO(N)．
//
// ============================================================
// 複数の集合をbitsetで持つ
//
// vector<bitset<MAX_N>> A(k);
//
// A[i].set(x);          // 集合Aiにxを追加
//
// bitset<MAX_N> U;
// for (int i=0; i<k; i++) {
//     U |= A[i];        // 全集合の和集合
// }
//
// 積集合の場合，初期値を全1にする方法もあるが，
// 未使用bitまで1になることに注意する．
//
// ============================================================
// 整数・文字列への変換
//
// B.to_string();       // "00101101"など
//
// 小さいbitsetなら
// B.to_ulong();
// B.to_ullong();
// で整数へ変換できる．
//
// 値が変換先整数型に収まらない場合は例外になるため，
// 大きなbitsetでは通常使用しない．
//
// ============================================================