#include <bits/stdc++.h>
#ifdef _WIN32
#include <windows.h>
#endif
using namespace std;

// ============================================================
// std::stack まとめ
//
// 使用頻度：★★★★☆
// 主な用途：LIFO，DFS，直前の状態を保存して戻る処理
// キーワード：stack，push，pop，top，LIFO，DFS
//
// 【基本】
// stack<int> st;
//
// LIFO（Last In First Out）．
// 最後に追加した要素から順番に取り出す．
//
// ============================================================
// 【主なメソッド・操作】
// stack<int> st;
//
// 〇要素の追加・削除
//   ・st.push(x);       // xを一番上に追加
//   ・st.emplace(...);  // 引数から要素を直接作成
//   ・st.pop();         // 一番上の要素を削除
//
// 〇要素の取得
//   ・st.top();         // 一番上の要素
//
// 〇要素数
//   ・st.size();        // 要素数
//   ・st.empty();       // 空ならtrue
//
// ※ top()，pop()は空のstackには使用しない．
// ============================================================

int main() {
#ifdef _WIN32
    SetConsoleOutputCP(CP_UTF8);
#endif

    cout << "##### stack #####\n";
    stack<int> st;

    cout << "10, 20, 30 をこの順にスタックに追加する\n";
    st.push(10);
    st.push(20);
    st.push(30);
    cout << "top(): " << st.top() << '\n';
    cout << "size(): " << st.size() << '\n';

    cout << "空になるまで取り出す．取り出す順番: ";
    while (!st.empty()) {
        int x = st.top();
        st.pop();
        cout << x << ' ';
    }
    cout << '\n';
    return 0;
}

// ============================================================
// 補足
// ============================================================
// LIFO（Last In First Out）
//
// stackは，最後に追加した要素を最初に取り出す．
//        top
//         ↓
//       [ 3 ]  ← 最後にpushした要素
//       [ 2 ]
//       [ 1 ]  ← 最初にpushした要素
//
//   追加：push()
//   取得：top()
//   削除：pop()
//
// 例えば，
//   st.push(1);
//   st.push(2);
//   st.push(3);
// とすると，pop()で削除する順番は
//   3 → 2 → 1
// となる．
//
// ============================================================
// DFSとstack
//
// 再帰を使わないDFSでは，これから処理する頂点をstackに保存する．
//
// stack<int> st;
// st.push(root);
// while (!st.empty()) {
//     int v = st.top();
//     st.pop();
//     for (int nv : adj[v]) {
//         ...
//         st.push(nv);
//     }
// }
//
// stackは最後に追加した頂点を次に処理するため，
// 深さ方向へ探索するDFSを実装できる．
//
// 再帰DFSでは，関数呼び出しをコールスタックが管理している．
// 明示的なstackを使えば，再帰を使わずに同様の探索ができ，
// 再帰の深さによるスタックオーバーフローを避けられる．
//
// 部分木サイズなど「帰りがけ」の処理が必要な場合は，
// 木DFSまとめの非再帰版を参照．
//
// ============================================================
// top()を参照で受けてからpopしない
//
// NG：
// auto& x = st.top();  // 参照受け
// st.pop();
//
// pop()によって一番上の要素が削除されるため，
// xは削除された要素を参照する無効な参照になる．
//
// OK：
// auto x = st.top();    // コピー
// st.pop();
//
// ============================================================
// push()とemplace()
//
// stack<pair<int, int>> st;
// st.push({1, 2});
// st.emplace(1, 2);
//
// どちらもpair{1, 2}を追加できる．
// 競プロではpush({a, b})でも十分短く，分かりやすい．
//
// ============================================================
// stackの中身を直接走査することはできない
//
// stackでは，
//   st[i]
//   st.begin()
//   for (auto x : st)
// のような操作はできない．
//
// 基本的にはtop()で一番上の要素だけを取得し，pop()しながら処理する．
// 中身を添字で扱いたい場合などは，vectorやdequeを使う．
//
// ============================================================
// stack，queue，deque
//
// stack
//   LIFO
//   最後に入れた要素を最初に取り出す
//   DFSで使用
// queue
//   FIFO
//   最初に入れた要素を最初に取り出す
//   BFSで使用
// deque
//   前後両方から追加・削除できる
//   0-1 BFSなどで使用
//
// ============================================================
// stackの内部コンテナ
//
// std::stackは，別のコンテナを利用してLIFOの操作だけを
// 公開する「コンテナアダプタ」．
//
// stack<int> st;
// と書いた場合，内部ではデフォルトでdeque<int>が使用される．
//
// 明示的に指定することもできる：
// stack<int, vector<int>> st;
//
// ただし，通常の競技プログラミングでは
// stack<int>とだけ書けば十分．
//
// ============================================================