#include <bits/stdc++.h>
using namespace std;
using ll = long long;

// ============================================================
// struct まとめ
//
// 使用頻度：★☆☆☆☆
// 主な用途：複数の値と，それらを扱う処理を1つの型としてまとめる
//
// ============================================================
#if 1

struct Point {
    ll x = 0, y = 0;

    // コンストラクタ
    Point() = default;                      // 引数なし
    Point(ll xx, ll yy) : x(xx), y(yy) {}   // 引数あり

    // メンバ関数
    ll sum() { return x + y; }
};

int main() {
    Point p(3, 5);          // コンストラクタを使用
    cout << p.x << ' ' << p.y << '\n';
    cout << "sum = " << p.sum() << '\n'; 
    return 0;
}

#endif

// ============================================================
// コンストラクタ
//
// struct Point {
//     ll x = 0, y = 0;
//     Point(ll xx, ll yy) : x(xx), y(yy) {}
// };
//
// Point p(3, 5);
// Point p{3, 5};            // {}でもよい
//
// 「: x(xx), y(yy)」は，引数xx, yyでメンバ変数x, yを初期化する．
//  他に処理が必要なときは，{}内に記述する．
//
// defaultを設定すれば，Point p; のように引数なしでも作れるようになる．
// この例では x=0, y=0 となる．
//
// ============================================================
// vectorの要素としても使用できる．
//
// vector<Point> P;
// P.push_back({3, 5});
// for (auto p : P) {
//     cout << p.x << ' ' << p.y << '\n';
// }
//
// ============================================================